// mothership:dev-only
//
// Writes the motion bible and event catalogue from their one source (design/cinematic/catalogue/
// catalogue.mjs): design/cinematic/catalogue/catalogue.json and docs/design/cinematic/motion-bible.md.
//   node design/tools/cinematic-docs.mjs

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATALOGUE, CATALOGUE_VERSION, CONTRACT, LIFECYCLE, REQUESTS } from '../cinematic/catalogue/catalogue.mjs';

const repoRoot = resolve(fileURLToPath(new URL('../../', import.meta.url)));
const json = resolve(repoRoot, 'design/cinematic/catalogue/catalogue.json');
const md = resolve(repoRoot, 'docs/design/cinematic/motion-bible.md');
await mkdir(dirname(md), { recursive: true });
await writeFile(json, `${JSON.stringify({ version: CATALOGUE_VERSION, contract: CONTRACT, lifecycle: LIFECYCLE, requests: REQUESTS, scenes: CATALOGUE }, null, 2)}\n`);

const cell = text => String(text ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const lines = [
  '# Motion bible and event catalogue',
  '',
  `Version \`${CATALOGUE_VERSION}\`. Generated by \`node design/tools/cinematic-docs.mjs\` from \`design/cinematic/catalogue/catalogue.mjs\`; the JSON twin is \`design/cinematic/catalogue/catalogue.json\`. Edit the module, not this file.`,
  '',
  `Contract: protocol ${CONTRACT.protocol}, engine \`${CONTRACT.engine}\`, ruleset \`${CONTRACT.ruleset}\`, \`${CONTRACT.file}\` at \`${CONTRACT.commit}\` (${CONTRACT.status}). Scene names are design labels, not API event types; a trigger the contract lacks is a named request below, and its scene stays a labeled design fixture until the contract supports it. Nothing here is a game rule.`,
  '',
  '## Lifecycle rules (every scene)',
  '',
  ...LIFECYCLE.map((rule, i) => `${i + 1}. ${rule}`),
  '',
  '## Contract requests for Integration',
  '',
  '| Id | Scene | Request |',
  '| --- | --- | --- |',
  ...REQUESTS.map(r => `| ${r.id} | ${r.scene} | ${cell(r.ask)} |`),
  '',
  '## Catalogue',
  '',
  '| Scene | Status | Audience | Trigger (contract) | Durations | Reduced motion |',
  '| --- | --- | --- | --- | --- | --- |',
  ...CATALOGUE.map(s => `| ${cell(s.scene)} | ${cell(s.status)} | ${cell(s.audience)} | ${cell(s.trigger)} | ${cell(Object.entries(s.durations).map(([k, v]) => `${k}: ${v}`).join('; '))} | ${cell(s.reduced)} |`),
  '',
];
for (const s of CATALOGUE) {
  lines.push(`### ${s.scene}`, '', `\`${s.id}\` · ${s.status}`, '');
  lines.push(`- **Trigger:** ${s.trigger}`);
  lines.push(`- **Audience:** ${s.audience}`);
  lines.push(`- **Fields:** ${s.fields.length ? s.fields.map(field => `\`${field}\``).join(', ') : 'none'}`);
  lines.push(`- **Start / loop / exit:** ${s.beats.start}; ${s.beats.loop}; ${s.beats.exit}`);
  lines.push(`- **Durations:** ${Object.entries(s.durations).map(([k, v]) => `${k} ${v}`).join('; ')}`);
  lines.push(`- **Final state:** ${s.final}`);
  lines.push(`- **Cancellation:** ${s.cancel}`);
  lines.push(`- **Precedence:** ${s.precedence}`);
  lines.push(`- **Audio:** ${s.audio}`);
  lines.push(`- **Reduced motion:** ${s.reduced}`);
  lines.push(`- **7 / 8 / 9 players:** ${s.rosters}`);
  lines.push(`- **Concurrent events:** ${s.concurrency}`);
  lines.push(`- **Existing art:** ${s.assets.length ? s.assets.map(a => `\`${a}\``).join(', ') : 'none yet'}`);
  lines.push(`- **Missing:** ${s.gaps.length ? s.gaps.join('; ') : 'nothing for this scene'}`);
  if (s.request) lines.push(`- **Contract request${[s.request].flat().length > 1 ? 's' : ''}:** ${[s.request].flat().join(', ')}`);
  lines.push('');
}
await writeFile(md, `${lines.join('\n')}\n`);
console.log(`${CATALOGUE.length} scenes, ${REQUESTS.length} requests -> ${json}, ${md}`);

// ---------- the inventory's gap map (docs/design/cinematic/inventory.md) ----------

const inventory = JSON.parse(await readFile(resolve(repoRoot, 'design/cinematic/inventory/inventory.json'), 'utf8'));
const contact = JSON.parse(await readFile(resolve(repoRoot, 'design/cinematic/inventory/contact-before-after.json'), 'utf8'));
const short = sha => (sha ? sha.slice(0, 12) : '');
const KEY_SOURCES = [
  ['Figure body and rig', 'design/board-motion/figures/body.mjs'], ['Rig', 'design/board-motion/figures/rig.mjs'], ['Crew', 'design/board-motion/figures/crew.mjs'],
  ['Gestures', 'design/board-motion/figures/gestures.mjs'], ['Motion (blend, walk)', 'design/board-motion/figures/motion.mjs'], ['Patient and prisoner clothing', 'design/board-motion/figures/wardrobe.mjs'],
  ['Scene framing', 'design/board-motion/scenes/frame.mjs'], ['Slots (roster ward)', 'design/board-v2/scenes/slots.mjs'], ['Slots (four beds)', 'design/board-v2/scenes/slots-four.mjs'],
  ['Hospital ward (roster)', 'design/board-v2/scenes/hospital-ward.mjs'], ['Hospital ward (four beds)', 'design/board-v2/scenes/hospital-ward-four.mjs'], ['Capsule scene', 'design/board-v2/scenes/capsule.mjs'],
  ['Capsule figures', 'design/board-v2/figures/capsule.mjs'], ['Capsule film (S2)', 'design/board-v2/films/capsule.mjs'], ['Lighting (Blackout)', 'design/board-v2/scenes/lighting.mjs'],
  ['Blackout film', 'design/board-v2/films/blackout.mjs'], ['Blocked impact (S4)', 'design/board-v2/fx/blocked.mjs'], ['Medical art', 'design/board-v2/fx/medical.mjs'],
  ['Medical (four beds)', 'design/board-v2/fx/medical-four.mjs'], ['Medical films (S5, S9, S10)', 'design/board-v2/films/medical.mjs'], ['Captain art', 'design/board-v2/fx/captain.mjs'],
  ['Captain films (S6, S7)', 'design/board-v2/films/captain.mjs'], ['Clone art', 'design/board-v2/fx/clone.mjs'], ['Clone film (S3)', 'design/board-v2/films/clone.mjs'],
  ['Overflow', 'design/board-v2/films/overflow.mjs'], ['Board fit (four beds)', 'design/board-v2/js/fit-four.mjs'], ['Turns (four beds)', 'design/board-v2/js/turns-four.mjs'],
];
const byPath = new Map(inventory.files.map(entry => [entry.path, entry]));
const inv = [
  '# Designer work inventory and gap map',
  '',
  'Generated by `node design/tools/cinematic-docs.mjs` from `design/cinematic/inventory/inventory.json` (written by `node design/tools/cinematic-inventory.mjs`, which reads git objects only and changes no checkout) and `design/cinematic/inventory/contact-before-after.json` (written by `node design/tools/cinematic-contact.mjs`).',
  '',
  `Scope: ${inventory.scope.map(p => `\`${p}\``).join(', ')}, across the runtime baseline, the design baseline and every Designer pull-request head. A file\'s *current* version is the newest Designer version by the chain precedence board-v2 > abilities > board-motion > phone-first > art-direction; its PR is the earliest Designer PR (by head time) holding that exact version.`,
  '',
  '## Heads read',
  '',
  '| Head | Commit | What |',
  '| --- | --- | --- |',
  ...inventory.heads.map(h => `| ${h.pr ? `#${h.pr}` : h.id} | \`${h.ref.slice(0, 12)}\` | ${cell(h.label ?? h.subject)} |`),
  '',
  '## Summary',
  '',
  '| Measure | Files |',
  '| --- | --- |',
  ...Object.entries(inventory.summary).map(([k, v]) => `| ${k} | ${v} |`),
  '',
  'Nothing on `main` is older than the Designer\'s version in any runtime registry (`runtimeOlderThanDesigner` 0): the runtime holds the newest reviewed Designer art for everything it registers. 824 Designer files are absent from `main` (unmerged PR work, mostly the board-v2 stack #128 to #161 and the review captures); none of them is reset or overwritten by this delivery.',
  '',
  '## Families',
  '',
  '| Family | Files | MB | Same on main | Absent from main | Main newer | Main older | Runtime registered (current) | Obsolete names | PRs |',
  '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
  ...inventory.families.map(fam => `| ${cell(fam.family)} | ${fam.files} | ${(fam.bytes / 1e6).toFixed(1)} | ${fam.identicalOnMain} | ${fam.absentFromMain} | ${fam.mainNewer} | ${fam.mainOlder} | ${fam.runtimeRegistered} (${fam.runtimeCurrent}) | ${fam.obsoleteNames} | ${(fam.prs ?? []).map(n => `#${n}`).join(' ')} |`),
  '',
  '## The brief\'s named source families: current versions',
  '',
  '| Source | Path | SHA-256 (12) | Bytes | First PR with this version | On main | Runtime use |',
  '| --- | --- | --- | --- | --- | --- | --- |',
  ...KEY_SOURCES.map(([label, path]) => {
    const e = byPath.get(path);
    if (!e) return `| ${label} | \`${path}\` | **missing** | | | | |`;
    const runtime = [...new Set((e.runtime ?? []).filter(r => r.runtime).map(r => `\`${r.runtime}\`${r.matchesDesigner === false ? ' (older)' : ''}`))].join(', ') || 'none registered';
    return `| ${label} | \`${path}\` | \`${short(e.current?.sha256)}\` | ${e.current?.size ?? ''} | ${e.current?.pr ? `#${e.current.pr}` : ''} | ${e.mainState} | ${runtime} |`;
  }),
  '',
  'Every named family is present; no source the brief names is missing.',
  '',
  '## Files where main and the Designer differ',
  '',
  'Ten files on `main` are newer than the Designer\'s last version: Integration (Codex) changed them after the Designer (drawing-port fences and checks for the reviewed ports). The Designer keeps them as `main` has them; this delivery does not touch them. Three files on `main` are older (the Designer\'s README, owner-decisions and the design-tokens manifest moved on in unmerged PRs).',
  '',
  '| Path | State |',
  '| --- | --- |',
  ...inventory.files.filter(e => /^main holds/.test(e.mainState ?? '')).map(e => `| \`${e.path}\` | ${e.mainState} |`),
  '',
  '## Names to correct',
  '',
  `${inventory.summary.withObsoleteNames} files still carry a superseded name: Cracker (now Doctor), Soldier Blue (now Engineer), Showdown and Final Zone (removed mechanics). They are historical art and review captures; current text uses the new names (design baseline 26947b1). Corrections ride the next asset group that touches each file, never a silent substitution. Library group 8 maps every current name to the art that draws it (\`design/library/successor/names.mjs\`): the files keep their historical ids and bytes.`,
  '',
  '## Before / after contact sheet',
  '',
  '![Before and after](../../../design/cinematic/inventory/contact-before-after.png)',
  '',
  '| Family | Before (main) | After (Designer current) |',
  '| --- | --- | --- |',
  ...contact.rows.map(r => `| ${cell(r.family)} | ${r.before ? `\`${r.before.path}\` \`${short(r.before.sha256)}\`` : 'none on main'} | \`${r.after.path}\` (${r.after.head}) \`${short(r.after.sha256)}\` |`),
  '',
  '## Gap map',
  '',
  'What the catalogue (docs/design/cinematic/motion-bible.md) still needs, by scene:',
  '',
  '| Scene | Status | Missing |',
  '| --- | --- | --- |',
  ...CATALOGUE.filter(s => s.gaps.length).map(s => `| ${cell(s.scene)} | ${cell(s.status)} | ${cell(s.gaps.join('; '))} |`),
  '',
];
await writeFile(resolve(repoRoot, 'docs/design/cinematic/inventory.md'), `${inv.join('\n')}\n`);
console.log('inventory.md written');
