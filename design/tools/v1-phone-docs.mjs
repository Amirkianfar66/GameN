// mothership:dev-only
//
// Writes docs/design/v1-phone-inventory.md from design/v1-phone/contract/journey.json:
//   node design/tools/v1-phone-docs.mjs
// The page is generated so that the inventory, the prototype and the screenshots cannot
// drift apart; design/tools/v1-phone-check.mjs refuses a page that is not what this writes.

import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(fileURLToPath(new URL('../../', import.meta.url)));
export const INVENTORY_PATH = 'docs/design/v1-phone-inventory.md';

const cell = text => String(text ?? '—').replace(/\|/g, '\\|').replace(/\n/g, ' ');

export async function planInventory(repo = repoRoot) {
  const journey = JSON.parse(await readFile(resolve(repo, 'design/v1-phone/contract/journey.json'), 'utf8'));
  const states = journey.screens.flatMap(screen => screen.states);
  const count = level => states.filter(state => state.runtime === level).length;
  const lines = [
    '# Phone-first V1 journey: screen and state inventory',
    '',
    `<!-- Generated by design/tools/v1-phone-docs.mjs from design/v1-phone/contract/journey.json (${journey.journeyVersion}). Do not edit by hand. -->`,
    '',
    `**${journey.status === 'proposal' ? 'A proposal' : journey.status}, not owner-approved.** Issue [#76](${journey.issue}). Design base \`${journey.designBase.commit}\` on \`${journey.designBase.branch}\` ([PR #75](${journey.designBase.pullRequest}), unmerged). Ruleset \`${journey.pins.rulesetVersion}\`, engine \`${journey.pins.engineVersion}\`, protocol ${journey.pins.protocolVersion}, setup lifecycle \`${journey.pins.setupLifecycle}\`, Original Powers off. Tokens ${journey.pins.tokenVersion}, assets \`${journey.pins.assetManifestVersion}\`, crew \`${journey.pins.crewCatalogVersion}\`.`,
    '',
    `${states.length} states on ${journey.screens.length} screens: **${count('existing')}** the release already produces (the design changes how they look), **${count('partial')}** need Frontend work only, **${count('proposed')}** need something the release does not have. Every state is drawn in the prototype from a labeled synthetic fixture with the same id; open one at \`/v1-phone/?state=<id>\` on the design review server. The journey map, the reasoning and the handoff are in [v1-phone-journey.md](v1-phone-journey.md) and [v1-phone-handoff.md](v1-phone-handoff.md).`,
    '',
    '## What the runtime column means',
    '',
    '| Level | Meaning |',
    '| --- | --- |',
    ...Object.entries(journey.runtimeLevels).map(([level, text]) => `| \`${level}\` | ${cell(text)} |`),
    '',
    '## Authorized data sources',
    '',
    '| Name | What it is, and who may read it |',
    '| --- | --- |',
    ...Object.entries(journey.dataSources).map(([name, text]) => `| \`${name}\` | ${cell(text)} |`),
    '',
  ];
  for (const screen of journey.screens) {
    lines.push(`## ${screen.priority ? `${screen.priority}. ` : ''}${screen.title}`, '', `Route: \`${screen.route}\`.${screen.priority ? ' One of the five priority screens.' : ''}`, '');
    if (screen.notStates) {
      lines.push('Not separate states, on purpose:', '', ...screen.notStates.map(text => `- ${text}`), '');
    }
    lines.push('| State | Surface · audience | Drawn from | In the release | Gap | Picture |', '| --- | --- | --- | --- | --- | --- |');
    for (const state of screen.states) {
      lines.push(`| \`${state.id}\`${state.priority ? ' ★' : ''}<br>${cell(state.title)} | ${state.surface} · ${state.audience} | ${state.data.map(source => `\`${source}\``).join(', ')} | **${state.runtime}**. ${cell(state.runtimeRef)} | ${cell(state.gap)} | [png](../../design/v1-phone/review/states/${state.id}.png) |`);
    }
    lines.push('');
  }
  lines.push('## Superseded examples', '', ...(journey.retiredStates ?? []).map(state => `- ${state.id}: ${state.reason}`),
    ...(journey.retiredComponents ?? []).map(component => `- ${component.id}: ${component.reason}`),
    '', `Retired release quote keys: ${(journey.retiredReleaseKeys ?? []).map(key => `\`${key}\``).join(', ')}. They are historical examples, excluded from current release copy and rendering. Required current quotes and verbatim source matching remain checked.`,
    '', `Current copy refresh: ${journey.copyRefresh?.sourceCommit ?? 'none'}; original design-base pin remains historical. Compact selection confirms on tile tap; joining takes a room code and uses the server-assigned room; the own setup surface is the role card plus Ready.`, '');
  lines.push('★ marks the states of the five priority screens shown on the priority contact sheet.', '',
    '## Components', '',
    'Reuse names the existing contract component (design/contract/component-states.json) or runtime hook the state is drawn on. Hooks marked PROPOSED are new.', '',
    '| Component | Reuse | Hook | Surfaces | Audience | What it is |', '| --- | --- | --- | --- | --- | --- |',
    ...journey.components.map(component => `| \`${component.id}\` | ${cell(component.reuse ?? 'new')} | \`${cell(component.hook)}\` | ${component.surfaces.join(', ')} | ${component.audience} | ${cell(component.about)} |`),
    '');
  return lines.join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await writeFile(resolve(repoRoot, INVENTORY_PATH), await planInventory());
  console.log(`Wrote ${INVENTORY_PATH}`);
}
