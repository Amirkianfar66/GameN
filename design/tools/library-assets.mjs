// mothership:dev-only
//
// Writes library group 1's art from its source (design/library/hack-engineer/art.mjs):
//   node design/tools/library-assets.mjs [--check]
// design/library/hack-engineer/assets/<name>.svg     each picture, standalone, transparent
// design/library/hack-engineer/assets/library.art.css every picture as a custom property (--lib-asset-<name>),
//                                                    as the dossier's abilities.art.css does: a page
//                                                    draws one only behind [data-art~="library"]
// design/library/hack-engineer/assets/manifest.json  name, version, size, role, about, SHA-256 and bytes
// --check writes nothing and fails if any file differs from what the source makes.

import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LIBRARY_ART_VERSION, libraryAssets } from '../library/hack-engineer/art.mjs';

const repoRoot = resolve(fileURLToPath(new URL('../../', import.meta.url)));
const out = resolve(repoRoot, 'design/library/hack-engineer/assets');
const sha256 = text => createHash('sha256').update(text).digest('hex');

/** An SVG as a CSS url() data URI: comments and the XML declaration dropped, the reserved characters escaped. */
export const dataUri = svg => `url("data:image/svg+xml,${svg.replace(/<\?xml[^>]*\?>/, '').replace(/<!--[\s\S]*?-->/g, '').trim()
  .replace(/"/g, '\'').replace(/%/g, '%25').replace(/#/g, '%23').replace(/</g, '%3C').replace(/>/g, '%3E').replace(/\s+/g, ' ')}")`;

export function build() {
  const assets = libraryAssets();
  const files = {};
  for (const [name, { svg }] of Object.entries(assets)) files[`${name}.svg`] = svg;
  files['library.art.css'] = `/* mothership:dev-only · library art proposal ${LIBRARY_ART_VERSION} · generated by design/tools/library-assets.mjs, do not edit.\n`
    + '   PRIVATE art: drawn only inside a seat\'s own open private sheet. Every player phone, once, with the ability art\n'
    + '   (design/abilities/assets/abilities.art.css), before the first match view, whatever the seat\'s role, state or turn.\n'
    + '   Every picture is a custom property; a page draws one only behind [data-art~="library"], set once this file has loaded. */\n'
    + `:root {\n${Object.entries(assets).map(([name, { svg }]) => `  --lib-asset-${name}: ${dataUri(svg)};`).join('\n')}\n}\n`;
  const manifest = {
    version: LIBRARY_ART_VERSION,
    generatedBy: 'design/tools/library-assets.mjs',
    source: 'design/library/hack-engineer/art.mjs',
    audience: 'private: the seat\'s own open private sheet; loaded whole on every player phone whatever the role',
    assets: Object.entries(assets).map(([name, { size, role, about }]) => ({ name, file: `design/library/hack-engineer/assets/${name}.svg`, size, role, about, sha256: sha256(files[`${name}.svg`]), bytes: Buffer.byteLength(files[`${name}.svg`]) })),
    stylesheet: { file: 'design/library/hack-engineer/assets/library.art.css', sha256: sha256(files['library.art.css']), bytes: Buffer.byteLength(files['library.art.css']) },
  };
  files['manifest.json'] = `${JSON.stringify(manifest, null, 2)}\n`;
  return files;
}

async function main() {
  const check = process.argv.includes('--check');
  const files = build();
  const stale = [];
  if (!check) await mkdir(out, { recursive: true });
  for (const [name, text] of Object.entries(files)) {
    const path = join(out, name);
    if (check) {
      const current = await readFile(path, 'utf8').catch(() => null);
      if (current !== text) stale.push(relative(repoRoot, path));
    } else {
      await writeFile(path, text);
    }
  }
  if (check && stale.length) { console.error(`Stale or missing: ${stale.join(', ')}. Run node design/tools/library-assets.mjs`); process.exit(1); }
  console.log(`${check ? 'checked' : 'wrote'} ${Object.keys(files).length} files in ${relative(repoRoot, out)}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
