// mothership:dev-only
//
// Writes docs/design/abilities-inventory.md from the ability-art inventory
// (design/abilities/contract/abilities.json) and the kit's manifest
// (design/abilities/assets/manifest.json). Node built-ins only.
//
//   node design/tools/abilities-docs.mjs

import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(fileURLToPath(new URL('../../', import.meta.url)));
const PATH = 'docs/design/abilities-inventory.md';
const cell = value => String(value).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const list = items => items.map(item => `- ${item}`).join('\n');

export async function planInventoryDoc(root = repoRoot) {
  const inventory = JSON.parse(await readFile(resolve(root, 'design/abilities/contract/abilities.json'), 'utf8'));
  const manifest = JSON.parse(await readFile(resolve(root, 'design/abilities/assets/manifest.json'), 'utf8'));
  const delivered = inventory.treatments.filter(entry => entry.status === 'delivered');
  const lines = [
    '<!-- Generated by design/tools/abilities-docs.mjs from design/abilities/contract/abilities.json and design/abilities/assets/manifest.json. Do not edit by hand. -->',
    '',
    '# Ability art and motion: the inventory',
    '',
    `\`mothership:dev-only\` · ${inventory.version} · ${inventory.status}`,
    '',
    inventory.about,
    '',
    `**Delivered:** ${delivered.length} of ${inventory.treatments.length} treatments (${delivered.map(entry => entry.title).join('; ')}). The rest are planned, slice by slice; each says what it will show and what it must never show.`,
    '',
    `**Base:** Designer \`${inventory.base.designerCommit.slice(0, 7)}\`, ruleset \`${inventory.base.ruleset}\` (parent \`${inventory.base.rulesetParent}\`), engine \`${inventory.base.engine}\`, protocol ${inventory.base.protocol}, tokens ${inventory.base.tokens}, reviewed assets \`${inventory.base.reviewedAssets}\`, board motion \`${inventory.base.boardMotion}\`. Original Powers ${inventory.base.originalPowers}.`,
    '',
    'Frontend instructions for the delivered treatments: [abilities-handoff.md](abilities-handoff.md).',
    '',
    '## Rules every treatment keeps',
    '',
    list(inventory.rules),
    '',
    '## The treatments',
    '',
    '| Treatment | Roles | Audience | Slice | Status |',
    '| --- | --- | --- | --- | --- |',
    ...inventory.treatments.map(entry => `| [${cell(entry.title)}](#${entry.id}) | ${cell(entry.roles.join(', '))} | ${cell(entry.audience)} | ${entry.slice} | ${entry.status} |`),
    '',
  ];
  for (const entry of inventory.treatments) {
    lines.push(`<a id="${entry.id}"></a>`, '', `### ${entry.title}`, '', `\`${entry.id}\` · slice ${entry.slice} · **${entry.status}** · ${entry.roles.join(', ')} · ${entry.audience}`, '',
      `**Trigger.** ${entry.trigger}`, '',
      `**View fields.** ${entry.fields.map(field => `\`${field}\``).join(', ')}`, '',
      '**What it must show, and never show.**', '', list(entry.disclosure), '',
      `**Concept.** ${entry.concept}`, '',
      `**Art.** ${entry.art.join('; ')}`, '',
      '| Motion | |', '| --- | --- |',
      ...['normal', 'reduced', 'static', 'cancel', 'replay'].map(form => `| ${form} | ${cell(entry.motion[form])} |`), '',
      `**States.** ${entry.states.join('; ')}`, '',
      `**Words.** ${entry.copy.visible.map(word => `“${word}”`).join(', ')}${entry.copy.accessible.length ? `. Accessible: ${entry.copy.accessible.map(word => `“${word}”`).join(', ')}` : ''}`, '');
    if (entry.review.length) lines.push(`**Review.** ${entry.review.map(path => `\`${path}\``).join(', ')}`, '');
    if (entry.dependencies.length) lines.push(`**Depends on.** ${entry.dependencies.join(' ')}`, '');
  }
  lines.push('## The kit', '',
    `Manifest \`${manifest.manifestVersion}\` (${manifest.status}), against the reviewed manifest \`${manifest.baseManifest}\` and tokens ${manifest.tokens}. Stylesheet \`${manifest.stylesheet.file}\`, ${manifest.stylesheet.bytes} bytes. ${manifest.bundle.loadPolicy}`, '',
    `**Rights.** ${manifest.rights}`, '',
    '| Asset | Version | Box | Anchors | Bytes | sha256 | Use |', '| --- | --- | --- | --- | --- | --- | --- |',
    ...manifest.assets.map(asset => `| \`${asset.id}\` | ${asset.version} | ${asset.width} x ${asset.height} | ${cell(Object.entries(asset.anchors).map(([key, value]) => `${key} ${JSON.stringify(value)}`).join('; '))} | ${asset.bytes} | \`${asset.sha256.slice(0, 12)}\` | ${cell(asset.use)} |`),
    '');
  return { path: PATH, content: `${lines.join('\n')}\n`.replace(/\n{3,}/g, '\n\n') };
}

const run = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (run) {
  const doc = await planInventoryDoc();
  await writeFile(resolve(repoRoot, doc.path), doc.content);
  console.log(`Wrote ${doc.path}`);
}
