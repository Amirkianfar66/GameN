// Writes docs/design/board-motion-coverage.md from the board-motion contracts and fixtures:
//   node design/tools/board-motion-docs.mjs
//   npm run docs:board-motion --workspace @mothership/design-tokens
// The page is generated so that the coverage matrix, the prototype and its captures cannot
// drift apart; design/tools/board-motion-check.mjs refuses a page that is not what this writes.

import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repoRoot = resolve(fileURLToPath(new URL('../../', import.meta.url)));
export const COVERAGE_PATH = 'docs/design/board-motion-coverage.md';
export const BASE = '94a49ce0c5220b814ec56333b028fbe6180b257e';

const cell = value => String(value ?? '—').replaceAll('|', '\\|').replaceAll('\n', ' ');
const row = cells => `| ${cells.map(cell).join(' | ')} |`;
const table = (head, rows) => [row(head), row(head.map(() => '---')), ...rows.map(row)];
const code = value => `\`${value}\``;
const png = path => `[png](../../${path})`;

/** The seats an action's scenario offers or shows as chosen, read from the fixture as the prototype reads it. */
function seatsOf(kind, state) {
  const offer = state.private.offers[kind];
  const offered = kind === 'code' ? (offer ? state.public.seats.map(seat => seat.n) : [])
    : kind === 'vote' ? (offer?.targets ?? [])
      : kind === 'release-vote' ? (state.public.ballot?.release ? [state.public.ballot.release] : [])
        : Array.isArray(offer) ? offer : [];
  const picked = (state.flow.kind === kind ? state.flow.picked ?? [] : []).filter(value => typeof value === 'number');
  return [...new Set([...offered, ...picked])];
}

export async function planCoverage(repo = repoRoot) {
  const json = async path => JSON.parse(await readFile(resolve(repo, path), 'utf8'));
  const coverage = await json('design/board-motion/contract/coverage.json');
  const cues = await json('design/board-motion/contract/cues.json');
  const stations = await json('design/board-motion/contract/stations.json');
  const manifest = await json('design/board-motion/assets/manifest.json');
  const { SCENARIOS, CREW } = await import(pathToFileURL(resolve(repo, 'design/board-motion/js/fixtures.js')).href);
  const scenario = id => SCENARIOS.find(entry => entry.id === id);
  const cueIds = new Set(cues.cues.map(cue => cue.id));

  const lines = [
    '# Board motion: coverage matrix',
    '',
    '<!-- Generated by design/tools/board-motion-docs.mjs from design/board-motion/contract/ (coverage.json, cues.json, stations.json), the prototype fixtures and the prop-layer manifest. Do not edit by hand. -->',
    '',
    `**Approved board-targeting direction; proposed prop/motion/figure adoption.** Issue [#87](https://github.com/Amirkianfar66/GameN/issues/87), ${coverage.version}. Design base ${code(BASE)} on ${code('codex/v1-pass-board-targets')} ([PR #86](https://github.com/Amirkianfar66/GameN/pull/86), unmerged): protocol 2, engine ${code('full-game-1.1.0')}, ruleset ${code('in-person-v1-pass-2026-10-08')}, Original Powers off. Tokens 0.4.0, assets ${code(manifest.baseManifest)} plus the prop layers ${code(manifest.manifestVersion)} (${manifest.status}).`,
    '',
    `Every action of the release is played on the comic board: chosen from a compact tray, its players picked by tapping their characters in their rooms, confirmed and answered in a strip above navigation. Moving is pressing a room's name; Pass is the middle of navigation. This page lists, for each of them, what the viewer's own view offers, how it is drawn, what is public and the cues that mark it; then every cue, the states every one of the nine characters has, the facts the board reads and where each comes from, the components and the runtime hooks they map onto, and the gaps. The reasoning and the integration steps are in [board-motion-handoff.md](board-motion-handoff.md); what was actually run is in [board-motion-verification.md](board-motion-verification.md).`,
    '',
    'Each scenario id opens in the prototype at `/board-motion/?scenario=<id>` on the design review server (`npm run dev:review --workspace @mothership/design-tokens`). Every name in it is synthetic.',
    'The offer guard checks applicable actor, round, phase, readiness and candidate predicates from the pinned engine and current overlays. It does not prove resources, prior-command history, runoff history or full engine reachability. Crowd fixtures are explicitly layout stress cases; they prove geometry only and introduce no room capacity or adjacency rule.',
    '',
    ...table(['Layout stress fixture', 'Purpose'], SCENARIOS.filter(entry => entry.status === 'layout-stress').map(entry => [code(entry.id), entry.title])),
    '',
    '## Actions',
    '',
    ...table(['Action', 'Offered by', 'On the board', 'Answers in the strip', 'Own character', 'Hospital and Jail', 'What is public', 'Cues', 'Scenarios'],
      coverage.actions.map(action => [`**${action.kind}** ${code(action.command)}`, action.offers, action.board, action.inline.length ? action.inline.join(' · ') : '—', action.self, action.hospitalJail, action.public,
        action.cues.map(code).join(' '), action.scenarios.map(code).join(' ')])),
    '',
    '## Every action with every character',
    '',
    'An action\'s rules never look at a character: the view offers seats, and whichever character sits in an offered seat is drawn eligible by the same rules (the check holds the stylesheet to it: a rule keyed by a character sets only its picture). This table says, from the fixtures themselves, in which scenarios each character is offered or chosen for each action; the crowd scenarios put every character the rules allow within reach in one room. A dash is a combination the rules exclude, and the last column says which and why. The vocabulary sheet ([vocabulary.png](../../design/board-motion/review/vocabulary.png)) draws all nine in every state. In these fixtures the viewer is Player 3, character c1.',
    '',
  ];
  const kinds = coverage.actions.filter(action => !['pass', 'move'].includes(action.kind));
  const why = {
    shot: 'The shooter\'s own character: an ordinary shot names another player.', disable: 'The Disabler\'s own character, as a Shot.', protect: 'None: Protection may name its giver.',
    rescue: 'None: the eight others in crowd.rescue, the Cracker\'s own injured character in rescue.self.', hack: 'The requester\'s own character: a Hack request names another player.', 'showdown-shot': 'The shooter\'s own character and the Eliminated (c9 in these fixtures).',
    scan: 'None.', supply: 'None.', code: 'None: every seat may be named.', vote: 'None.',
    'release-choice': 'Everyone not in the Jail: only jailed players may be asked for.', 'release-vote': 'Everyone but the subject: the subject is marked, nobody is picked.',
  };
  lines.push(...table(['Action', ...CREW.map(entry => `${entry.id} ${entry.sign}`), 'Why a fixture offers only some'], kinds.map(action => {
    const hits = new Map(CREW.map(entry => [entry.id, []]));
    for (const id of action.scenarios) {
      const entry = scenario(id);
      if (!entry) continue;
      const state = entry.s();
      for (const n of seatsOf(action.kind, state)) hits.get(state.public.seats.find(seat => seat.n === n).character)?.push(id);
    }
    return [`**${action.kind}**`, ...CREW.map(entry => (hits.get(entry.id).length ? hits.get(entry.id).map(code).join(' ') : '—')), why[action.kind] ?? ''];
  })), '');
  lines.push('Pass names no one. Move names a room, never a character: the viewer\'s own piece is the one that moves, and every character\'s move is drawn by `cue-public-move` with its own lift and settle (below).', '');

  lines.push('## The states of every character', '', cell(coverage.vocabulary.about), '',
    ...table(['State', 'Drawn', 'Cue'], coverage.vocabulary.states.map(state => [code(state.id), state.drawn, state.cue ? code(state.cue) : 'none: a state, not a motion'])), '',
    'The one public flourish that differs per character is in a move: how high it is lifted and how it settles (fixtures `CREW`, public, never a role).', '',
    ...table(['Character', 'Call sign', 'Lift (px)', 'Settle (deg)'], CREW.map(entry => [code(entry.id), entry.sign, entry.hop, entry.settle])), '',
    `All nine in all ${coverage.vocabulary.states.length} states: ${png('design/board-motion/review/vocabulary.png')}.`, '');

  lines.push('## Cues', '', cell(cues.about), '', 'Rules every cue keeps:', '', ...cues.rules.map(rule => `- ${rule}`), '',
    ...table(['Cue', 'Status', 'Trigger', 'Audience and facts', 'Anchor', 'Timing', 'Cancelled by', 'Settled state', 'Reduced motion', 'Asset'],
      cues.cues.map(cue => [`${code(cue.id)}<br>${cue.level}`, cue.status === 'authorized' ? `reviewed: ${cue.reviewed}` : 'proposal', cue.trigger, `**${cue.audience}**. ${cue.facts}`, code(cue.anchor),
        cue.durationMs ? `${cue.durationMs} ms (${cue.token}), ${cue.easing}` : 'none: a state', cue.cancellation, cue.settled, cue.reduced, cue.asset])), '',
    'Not produced, on purpose:', '', ...table(['What', 'Why'], cues.notProduced.map(item => [item.what, item.why])), '');

  lines.push('## Facts and where they come from', '', cell(coverage.facts.about), '',
    ...table(['Fact', 'Drawn', 'Source at the pinned tuple', 'Audience', 'Cues'], coverage.facts.list.map(fact => [code(fact.id), fact.drawn, fact.source, fact.audience, fact.cues.map(code).join(' ') || '—'])), '');

  lines.push('## Rooms and stations', '',
    `Every room has a hand-placed formation for each count from one to five occupants, in the places the reference page puts people (behind the chart table, at a console, in the bed, on the bench); six to nine in one room stand in a 3 x 3 crowd. A station is worked out on every device from public occupancy and seat order (${code('design/board-motion/js/layout.js')}), so every screen draws the same. No capacity is implied: see GAP-2.`, '',
    ...table(['Room', 'Stations', 'Formations, by count', 'Picture crop'], Object.entries(stations.rooms).filter(([, spec]) => Object.keys(spec.stations).length).map(([room, spec]) => [`${spec.location} (${code(room)})`,
      Object.entries(spec.stations).map(([id, station]) => `${id}: ${station.about}${station.kind === 'prop' ? ` (behind the prop, ${station.pose})` : station.kind === 'seat' ? ` (seated in the picture, ${station.pose})` : ''}`).join('; '),
      Object.entries(spec.formations).map(([count, ids]) => `${count}: ${ids.join(' ')}`).join(' · '),
      spec.view ? `center ${spec.view.cx}, width ${spec.view.cw}, anchor line ${spec.view.edge} at ${spec.view.at}` : '—'])), '');

  lines.push('## Components and runtime hooks', '', cell(coverage.components.about), '',
    ...table(['Component', 'Prototype', 'Release hook', 'Status', 'Audience', 'What it is'], coverage.components.list.map(component => [code(component.id), code(component.prototype), component.runtime === 'none' ? '—' : code(component.runtime), component.status, component.audience, component.about])), '');

  lines.push('## Gaps and open decisions', '', cell(coverage.gaps.about), '', ...table(['Id', 'Kind', 'What', 'In this design'], coverage.gaps.list.map(gap => [gap.id, gap.kind, gap.what, gap.decision])), '');

  lines.push('## Prop layers', '', `${cell(manifest.note)} Rights: ${cell(manifest.rights.origin)} ${cell(manifest.rights.reuse)}`, '',
    ...table(['Layer', 'From', 'Elements', 'Proposed export variant', 'Bytes'], manifest.assets.map(asset => [code(asset.file), `${code(asset.source)} group ${code(asset.group)}`, asset.selection.elements, code(asset.proposedExportVariant), asset.bytes])), '');

  const missing = coverage.actions.flatMap(action => action.cues.filter(id => !cueIds.has(id)).map(id => `${action.kind}: ${id}`));
  if (missing.length) throw new Error(`Unknown cues in coverage.json: ${missing.join(', ')}`);
  return `${lines.join('\n').trimEnd()}\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await writeFile(resolve(repoRoot, COVERAGE_PATH), await planCoverage());
  console.log(`Wrote ${COVERAGE_PATH}`);
}
